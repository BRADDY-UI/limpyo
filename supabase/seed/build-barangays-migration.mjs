#!/usr/bin/env node
// Turns supabase/seed/barangays.geojson into the data migration that loads the 26 barangays.
// Run: node supabase/seed/build-barangays-migration.mjs > supabase/migrations/20261114000003_barangays.sql
// Boundaries come from OpenStreetMap (ODbL); see the "note" in the GeoJSON for how they were made.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fc = JSON.parse(readFileSync(join(here, "barangays.geojson"), "utf8"));
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const features = [...fc.features].sort((a, b) => a.properties.name.localeCompare(b.properties.name));
if (features.length !== 26) throw new Error(`expected 26 barangays, got ${features.length}`);

const rows = features.map((f, i) => {
  const [lon, lat] = f.properties.center;
  if (![lon, lat].every(Number.isFinite)) throw new Error(`bad center for ${f.properties.name}`);
  const geom = JSON.stringify(f.geometry);
  return `  (${i + 1}, ${lit(f.properties.name)}, ${lit(slug(f.properties.name))},
   extensions.st_multi(extensions.st_setsrid(extensions.st_geomfromgeojson(${lit(geom)}), 4326))::extensions.geography,
   extensions.st_setsrid(extensions.st_makepoint(${lon}, ${lat}), 4326)::extensions.geography,
   ${f.properties.approximate ? "true" : "false"})`;
});

process.stdout.write(`-- 0003 barangays (Phase 1A) - GENERATED by supabase/seed/build-barangays-migration.mjs
-- The 26 barangays of General Santos City. Boundaries are APPROXIMATE (see supabase/seed/barangays.geojson).
-- Map data (c) OpenStreetMap contributors, ODbL 1.0.
insert into public.barangays (id, name, slug, boundary, centroid, approximate) values
${rows.join(",\n")};
`);
